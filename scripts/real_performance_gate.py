def _terminate_load_process(
    process: subprocess.Popen[str],
    *,
    wait_seconds: float = CHILD_TERMINATION_WAIT_SECONDS,
) -> tuple[bool, str | None]:
    """Terminate only our child and turn every wait failure into evidence.

    ``Popen.wait`` can still time out after ``kill`` (notably when the child
    has a detached descendant or the OS is under pressure).  The acceptance
    script must report that state instead of allowing an uncaught exception
    to escape.  We deliberately do not attempt a process-tree kill here.
    """

    try:
        process.kill()
    except (OSError, ProcessLookupError) as error:
        try:
            if process.poll() is not None:
                return True, None
        except (OSError, ProcessLookupError):
            pass
        return False, type(error).__name__
    try:
        process.wait(timeout=wait_seconds)
    except subprocess.TimeoutExpired:
        return False, "TimeoutExpired"
    except (OSError, ProcessLookupError) as error:
        return False, type(error).__name__
    return True, None


def _mark_unconfirmed_termination(
    report: dict[str, Any],
    *,
    error_type: str | None,
) -> None:
    """Make a report fail closed when child cleanup cannot be confirmed."""

    candidate = report.setdefault("candidate", {})
    if not isinstance(candidate, dict):
        candidate = {}
        report["candidate"] = candidate
    supervision = candidate.setdefault("supervision", {})
    if not isinstance(supervision, dict):
        supervision = {}
        candidate["supervision"] = supervision
    supervision["cleanup_termination"] = {
        "status": "unconfirmed",
        "wait_seconds": CHILD_TERMINATION_WAIT_SECONDS,
        "error_type": error_type,
    }
    report["gate"] = "fail"
    report["production_gate"] = "fail"
    for key in ("rejection_reasons", "production_rejection_reasons"):
        reasons = report.setdefault(key, [])
        if not isinstance(reasons, list):
            reasons = []
            report[key] = reasons
        reason = "load generator child termination could not be confirmed"
        if reason not in reasons:
            reasons.append(reason)


def _run_external_load(args: argparse.Namespace, preflight: dict[str, Any]) -> dict[str, Any]:
    """Supervise exactly one load-generator process and never mutate Docker."""

    run_id = f"real-performance-{uuid4().hex}"
    process_timeout_seconds = _hard_process_timeout(args)
    worker_token = uuid4().hex
    process: subprocess.Popen[str] | None = None
    result: dict[str, Any] | None = None
    with tempfile.TemporaryDirectory(prefix=f".{run_id}-") as temporary_directory:
        output = Path(temporary_directory) / "load-result.json"
        child_environment = os.environ.copy()
        child_environment[WORKER_TOKEN_ENV] = worker_token
        child_environment["TRPC_REAL_RUN_ID"] = run_id
        child_environment[PARENT_PID_ENV] = str(os.getpid())
        command = _load_worker_command(args, output)
        try:
            process = subprocess.Popen(  # noqa: S603 - fixed self-load-worker command
                command,
                cwd=ROOT,
                env=child_environment,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                text=True,
            )
            try:
                return_code = process.wait(timeout=process_timeout_seconds)
            except subprocess.TimeoutExpired:
                # The only permitted termination is our own load-worker child.
                terminated, termination_error = _terminate_load_process(process)
                reason = "load generator exceeded its hard timeout"
                if not terminated:
                    reason += " and did not terminate within the safety wait"
                result = _supervision_failure(
                    args,
                    preflight,
                    reason,
                    run_id=run_id,
                    process_timeout_seconds=process_timeout_seconds,
                )
                result["candidate"]["supervision"]["termination"] = {
                    "status": "terminated" if terminated else "unconfirmed",
                    "wait_seconds": CHILD_TERMINATION_WAIT_SECONDS,
                    "error_type": termination_error,
                }
                return result
            try:
                report = json.loads(output.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                result = _supervision_failure(
                    args,
                    preflight,
                    "load generator did not produce valid report evidence",
                    run_id=run_id,
                    process_timeout_seconds=process_timeout_seconds,
                )
                return result
            if not isinstance(report, dict):
                result = _supervision_failure(
                    args,
                    preflight,
                    "load generator report root must be an object",
                    run_id=run_id,
                    process_timeout_seconds=process_timeout_seconds,
                )
                return result
            candidate = report.setdefault("candidate", {})
            if not isinstance(candidate, dict):
                result = _supervision_failure(
                    args,
                    preflight,
                    "load generator candidate evidence must be an object",
                    run_id=run_id,
                    process_timeout_seconds=process_timeout_seconds,
                )
                return result
            candidate["run_id"] = run_id
            supervision_status = "pass" if return_code == 0 else "fail"
            candidate["supervision"] = {
                "status": supervision_status,
                "load_generator": "single_external_process",
                "process_timeout_seconds": process_timeout_seconds,
            }
            if return_code != 0:
                report["gate"] = "fail"
                report["production_gate"] = "fail"
                report.setdefault("rejection_reasons", []).append(
                    "load generator exited with a non-zero status"
                )
                report.setdefault("production_rejection_reasons", []).append(
                    "load generator exited with a non-zero status"
                )
            result = report
            return result
        except (OSError, ValueError):
            result = _supervision_failure(
                args,
                preflight,
                "load generator process could not be started safely",
                run_id=run_id,
                process_timeout_seconds=process_timeout_seconds,
            )
            return result
        except Exception:
            # Keep an unexpected supervisor error report-safe and fail closed;
            # the finally block below still records any unconfirmed cleanup.
            result = _supervision_failure(
                args,
                preflight,
                "load generator supervision raised an unexpected error",
                run_id=run_id,
                process_timeout_seconds=process_timeout_seconds,
            )
            return result
        finally:
            process_running = False
            if process is not None:
                try:
                    process_running = process.poll() is None
                except (OSError, ProcessLookupError):
                    process_running = True
            if process is not None and process_running:
                # Never stop or remove the service under test here.  A
                # leftover child is reported in the returned evidence; the
                # cleanup path also remains exception-safe.
                try:
                    terminated, termination_error = _terminate_load_process(process)
                except Exception as error:
                    terminated = False
                    termination_error = type(error).__name__
                if not terminated and result is not None:
                    _mark_unconfirmed_termination(
                        result,
                        error_type=termination_error,
                    )


async def _prewarm_pool(pool: asyncpg.Pool) -> None:
    async with pool.acquire() as connection:
        await connection.execute("SELECT 1")


async def _staged_warmup(
    runtime: TenantRuntime,
    route: BindingRoute,
    pool: asyncpg.Pool,
    redis: Any,
    *,
    binding_id: str,
    tenant_id: str,
    baseline_pending: int,
    stream: str,
    group: str,
    run_id: str,
    max_inflight: int,
    timeout_seconds: float,
    target_turns: int | None = None,
    scheduler_version: SchedulerVersion = SchedulerVersion.V1,
) -> tuple[tuple[dict[str, Any], ...], bool]:
    """Increase load in small steps before the locked acceptance phases."""

    observations: list[dict[str, Any]] = []
    warmup_timeout = min(timeout_seconds, 30.0)
    bounded_target = (
        max(1, int(target_turns)) if target_turns is not None and int(target_turns) > 0 else None
    )
    for index, configured_count in enumerate(DEFAULT_WARMUP_STEPS):
        count = (
            min(configured_count, bounded_target)
            if bounded_target is not None
            else configured_count
        )
        phase = await _submit_batch(
            runtime,
            route,
            binding_id=binding_id,
            prefix=f"{run_id}-warmup-{index}",
            count=count,
            offered_rate=min(float(10 * (index + 1)), MAX_CALLBACK_RATE),
            max_inflight=min(max_inflight, count),
            timeout_seconds=warmup_timeout,
        )
        completion = await _wait_for_batch(
            pool,
            redis,
            tenant_id=tenant_id,
            inbound_ids=phase["inbound_ids"],
            session_ids=phase["session_ids"],
            baseline_pending=baseline_pending,
            stream=stream,
            group=group,
            wait_seconds=warmup_timeout,
            scheduler_version=scheduler_version,
        )
        observation = {
            "requested": count,
            "accepted": phase["accepted"],
            "errors": phase["errors"],
            "completion": completion,
        }
        observations.append(observation)
        if phase["errors"] or completion.get("status") != "pass":
            return tuple(observations), False
    return tuple(observations), True


