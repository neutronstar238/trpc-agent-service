def _git_evidence() -> dict[str, Any]:
    """Capture non-sensitive Git identity and dirty-state evidence."""

    git = shutil.which("git")
    if git is None:
        return {"status": "unavailable", "reason": "git executable not found"}
    try:
        head = subprocess.run(  # noqa: S603 - fixed executable and arguments
            [git, "rev-parse", "--verify", "HEAD"],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=5,
        )
        status = subprocess.run(  # noqa: S603 - fixed executable and arguments
            [git, "status", "--porcelain=v1", "--untracked-files=all"],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=5,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        return {"status": "unavailable", "error_type": type(error).__name__}
    if head.returncode != 0 or status.returncode != 0:
        return {"status": "unavailable", "reason": "git command failed"}
    status_text = status.stdout
    status_lines = [line for line in status_text.splitlines() if line]
    status_digest = hashlib.sha256(status_text.encode("utf-8")).hexdigest()
    return {
        "status": "available",
        "head": head.stdout.strip() or None,
        "dirty": bool(status_lines),
        "changed_file_count": len(status_lines),
        "untracked_file_count": sum(line.startswith("?? ") for line in status_lines),
        "status_sha256": status_digest,
    }


def _runtime_inputs_from_report(
    report: Mapping[str, Any],
    *,
    stream: str | None = None,
    group: str | None = None,
) -> dict[str, Any] | None:
    """Extract only the inputs needed to build a safe runtime fingerprint."""

    candidate = report.get("candidate")
    if not isinstance(candidate, Mapping):
        return None
    preflight = candidate.get("preflight")
    parameters = candidate.get("parameters")
    if not isinstance(preflight, Mapping) or not isinstance(parameters, Mapping):
        return None
    workers = preflight.get("worker_processes")
    if not isinstance(workers, list) or not workers:
        return None
    mode = candidate.get("mode")
    if not isinstance(mode, str) or not mode:
        return None
    return {
        "mode": mode,
        "worker_identities": workers,
        "stream": stream,
        "group": group,
        "parameters": dict(parameters),
    }


def _evidence_metadata(
    report: Mapping[str, Any] | None = None,
    *,
    run_id: str | None = None,
    runtime_inputs: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Return versioned current-candidate evidence safe to persist."""

    runtime: dict[str, Any] | None = None
    if runtime_inputs is not None:
        runtime = runtime_fingerprint(
            mode=cast(str | None, runtime_inputs.get("mode")),
            worker_identities=cast(Sequence[Any] | None, runtime_inputs.get("worker_identities")),
            stream=cast(str | None, runtime_inputs.get("stream")),
            group=cast(str | None, runtime_inputs.get("group")),
            parameters=cast(Mapping[str, Any] | None, runtime_inputs.get("parameters")),
        )
    elif report is not None:
        inferred = _runtime_inputs_from_report(report)
        if inferred is not None:
            runtime = runtime_fingerprint(
                mode=cast(str | None, inferred.get("mode")),
                worker_identities=cast(Sequence[Any] | None, inferred.get("worker_identities")),
                stream=cast(str | None, inferred.get("stream")),
                group=cast(str | None, inferred.get("group")),
                parameters=cast(Mapping[str, Any] | None, inferred.get("parameters")),
            )
    evidence = build_evidence(
        root=ROOT,
        producer="scripts.real_performance_gate",
        run_id=run_id,
        runtime=runtime,
        source_roots=SOURCE_FINGERPRINT_ROOTS,
        max_files=FINGERPRINT_MAX_FILES,
        max_bytes=FINGERPRINT_MAX_BYTES,
    )
    # Git metadata is intentionally limited to a commit ID, dirty bit, and a
    # status digest; it does not contain source contents or environment data.
    evidence["git"] = _git_evidence()
    return evidence


def _scheduler_transport(
    args: argparse.Namespace | None = None,
) -> tuple[SchedulerVersion, str, str]:
    """Resolve and validate the scheduler wire version and Redis names.

    The performance gate writes through ``TenantRuntime`` and observes the
    same Redis transport used by the workers.  A mismatched version/stream/
    group would otherwise make a run look empty while accepting messages into
    a different scheduler.  Standard v1 compatibility therefore remains
    available only as one complete, explicitly selected transport set.
    """

    raw_version: Any = (
        getattr(args, "scheduler_version", DEFAULT_SCHEDULER_VERSION)
        if args is not None
        else DEFAULT_SCHEDULER_VERSION
    )
    if isinstance(raw_version, SchedulerVersion):
        version = raw_version
    else:
        try:
            version = SchedulerVersion(str(raw_version))
        except ValueError as error:
            raise ValueError("scheduler version must be v1 or v2") from error

    raw_stream = getattr(args, "redis_stream", None) if args is not None else None
    raw_group = getattr(args, "redis_group", None) if args is not None else None
    if (raw_stream is None) != (raw_group is None):
        raise ValueError("redis stream and consumer group must be configured together")
    if raw_stream is not None and (
        not isinstance(raw_stream, str)
        or not raw_stream.strip()
        or not isinstance(raw_group, str)
        or not raw_group.strip()
    ):
        raise ValueError("redis stream and consumer group must be non-empty strings")

    standard = {
        SchedulerVersion.V1: (V1_STREAM, V1_GROUP),
        SchedulerVersion.V2: (V2_STREAM, V2_GROUP),
    }
    default_stream, default_group = standard[version]
    stream = default_stream if raw_stream is None else raw_stream
    group = default_group if raw_group is None else raw_group

    for standard_version, (standard_stream, standard_group) in standard.items():
        mentions_standard_name = stream == standard_stream or group == standard_group
        if not mentions_standard_name:
            continue
        if version != standard_version or (stream, group) != (
            standard_stream,
            standard_group,
        ):
            raise ValueError(
                "scheduler version, Redis stream, and consumer group must be a matching set"
            )
    return version, stream, group


def _apply_scheduler_transport(args: argparse.Namespace) -> tuple[SchedulerVersion, str, str]:
    """Resolve transport once and retain canonical values on the argument namespace."""

    version, stream, group = _scheduler_transport(args)
    args.scheduler_version = version.value
    args.redis_stream = stream
    args.redis_group = group
    return version, stream, group


