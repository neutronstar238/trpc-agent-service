def _compose_worker_processes(project: str) -> tuple[dict[str, int | str], ...]:
    """Discover running workers and their immutable image identity.

    Container IDs, image IDs, and the candidate source label are read from a
    read-only ``docker inspect`` call.  A PID-only record is intentionally not
    synthesized here: it may be useful for a bounded local run, but it cannot
    establish which image is serving the workload.
    """

    docker = shutil.which("docker")
    if docker is None:
        return ()
    try:
        listed = subprocess.run(  # noqa: S603 - fixed Docker executable and labels
            [
                docker,
                "ps",
                "--filter",
                f"label=com.docker.compose.project={project}",
                "--filter",
                "label=com.docker.compose.service=worker",
                "--format",
                "{{.ID}}",
            ],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ()
    if listed.returncode != 0:
        return ()
    workers: list[dict[str, int | str]] = []
    seen_pids: set[int] = set()
    seen_containers: set[str] = set()
    for container_id in (line.strip() for line in listed.stdout.splitlines()):
        if not container_id or container_id in seen_containers:
            continue
        seen_containers.add(container_id)
        try:
            inspected = subprocess.run(  # noqa: S603 - ID came from Docker itself
                [
                    docker,
                    "inspect",
                    "--format",
                    "{{json .}}",
                    container_id,
                ],
                cwd=ROOT,
                check=False,
                capture_output=True,
                text=True,
                timeout=10,
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        if inspected.returncode != 0:
            continue
        try:
            details = json.loads(inspected.stdout)
        except (TypeError, ValueError):
            continue
        if not isinstance(details, Mapping):
            continue
        state = details.get("State")
        config = details.get("Config")
        if not isinstance(state, Mapping) or not isinstance(config, Mapping):
            continue
        labels = config.get("Labels")
        if labels is None:
            labels = {}
        if not isinstance(labels, Mapping):
            continue
        if state.get("Running") is not True:
            continue
        try:
            pid = int(state.get("Pid", 0))
        except (TypeError, ValueError):
            continue
        if pid > 1 and pid not in seen_pids:
            seen_pids.add(pid)
            inspected_container_id = details.get("Id")
            image_id = details.get("Image")
            source_fingerprint = labels.get(IMAGE_SOURCE_FINGERPRINT_LABEL)
            worker: dict[str, int | str] = {
                "container_id": (
                    inspected_container_id
                    if isinstance(inspected_container_id, str) and inspected_container_id
                    else container_id
                ),
                "pid": pid,
            }
            if isinstance(image_id, str) and image_id:
                worker["image_id"] = image_id
                # ``.Image`` is Docker's immutable content-addressed image ID;
                # retain the digest alias so reports are explicit about what
                # was inspected without recording command output.
                worker["image_digest"] = image_id
            if isinstance(source_fingerprint, str):
                worker["source_fingerprint"] = source_fingerprint
            workers.append(worker)
    return tuple(workers)


def _worker_image_attestation(
    workers: Sequence[Mapping[str, Any]],
    current_source: Mapping[str, Any],
) -> dict[str, Any]:
    """Validate that all discovered workers serve one current candidate image."""

    if not workers:
        return {
            "status": "not_run",
            "reason": "no worker containers were available for image attestation",
        }

    source_value = current_source.get("value")
    if (
        current_source.get("algorithm") != "sha256"
        or current_source.get("status") != "available"
        or not isinstance(source_value, str)
        or _SHA256_RE.fullmatch(source_value) is None
    ):
        return {
            "status": "not_run",
            "reason": "current checkout source fingerprint is unavailable",
        }

    missing_fields: set[str] = set()
    image_ids: set[str] = set()
    source_labels: set[str] = set()
    for worker in workers:
        container_id = worker.get("container_id")
        image_id = worker.get("image_id")
        label = worker.get("source_fingerprint")
        if not isinstance(container_id, str) or not container_id.strip():
            missing_fields.add("container_id")
        if (
            not isinstance(image_id, str)
            or _IMAGE_DIGEST_RE.fullmatch(image_id) is None
        ):
            missing_fields.add("image_id")
        else:
            image_ids.add(image_id)
        if not isinstance(label, str) or _SHA256_RE.fullmatch(label) is None:
            missing_fields.add("source_fingerprint")
        else:
            source_labels.add(label)

    if missing_fields:
        return {
            "status": "not_run",
            "reason": "worker image attestation is missing or invalid: "
            + ", ".join(sorted(missing_fields)),
        }
    if len(image_ids) != 1:
        return {
            "status": "not_run",
            "reason": "worker containers are using mixed image IDs",
            "image_count": len(image_ids),
        }
    if source_labels != {source_value}:
        return {
            "status": "not_run",
            "reason": "worker image source fingerprint label is stale or mixed",
            "label_count": len(source_labels),
        }
    return {
        "status": "pass",
        "worker_count": len(workers),
        "image_count": 1,
        "source_fingerprint_matches": True,
    }


def _windows_pid_alive(pid: int) -> bool:
    """Probe a Windows PID without sending a signal or modifying the process."""

    import ctypes
    from ctypes import wintypes

    process_query_limited_information = 0x1000
    still_active = 259
    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    open_process = kernel32.OpenProcess
    open_process.argtypes = (wintypes.DWORD, wintypes.BOOL, wintypes.DWORD)
    open_process.restype = wintypes.HANDLE
    get_exit_code = kernel32.GetExitCodeProcess
    get_exit_code.argtypes = (wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD))
    get_exit_code.restype = wintypes.BOOL
    close_handle = kernel32.CloseHandle
    close_handle.argtypes = (wintypes.HANDLE,)
    close_handle.restype = wintypes.BOOL

    handle = open_process(process_query_limited_information, False, pid)
    if not handle:
        return False
    try:
        exit_code = wintypes.DWORD()
        queried = bool(get_exit_code(handle, ctypes.byref(exit_code)))
        return queried and exit_code.value == still_active
    finally:
        close_handle(handle)


def _pid_alive(pid: int) -> bool:
    if pid <= 1:
        return False
    if os.name == "nt":
        return _windows_pid_alive(pid)
    proc_stat = Path(f"/proc/{pid}/stat")
    if proc_stat.exists():
        try:
            # The command name may contain spaces and closing parentheses;
            # the state field is the first token after the final ')'.
            raw_stat = proc_stat.read_text(encoding="ascii")
            _, separator, tail = raw_stat.rpartition(")")
            if not separator:
                return False
            state_fields = tail.strip().split(maxsplit=1)
            return bool(state_fields) and state_fields[0] != "Z"
        except (OSError, UnicodeError):
            # An existing but unreadable stat file is not safe evidence of a
            # live parent/worker, so fail closed.
            return False
    try:
        os.kill(pid, 0)
    except (OSError, ProcessLookupError):
        return False
    return True


def _worker_processes() -> tuple[dict[str, int | str], ...]:
    """Find independent worker PIDs without requiring psutil or Docker."""

    real_compose_project = os.getenv("TRPC_REAL_COMPOSE_PROJECT", "").strip()
    performance_compose_project = os.getenv("TRPC_PERF_COMPOSE_PROJECT", "").strip()
    if (
        real_compose_project
        and performance_compose_project
        and real_compose_project != performance_compose_project
    ):
        return ()

    explicit = os.getenv("TRPC_REAL_WORKER_PIDS", "").strip()
    if explicit:
        explicit_processes: list[dict[str, int | str]] = []
        seen_pids: set[int] = set()
        for value in explicit.split(","):
            try:
                pid = int(value.strip())
            except ValueError:
                continue
            if pid > 1 and pid not in seen_pids and _pid_alive(pid):
                seen_pids.add(pid)
                explicit_processes.append({"pid": pid})
        return tuple(explicit_processes)

    compose_project = real_compose_project or performance_compose_project
    if compose_project:
        return _compose_worker_processes(compose_project)

    ps = shutil.which("ps")
    if ps is None:
        return ()
    try:
        completed = subprocess.run(  # noqa: S603 - fixed process inspection command
            [ps, "-eo", "pid=,args="],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ()
    if completed.returncode != 0:
        return ()
    processes: list[dict[str, int | str]] = []
    process_seen_pids: set[int] = set()
    for line in completed.stdout.splitlines():
        match = re.match(r"\s*(\d+)\s+(.*)$", line)
        if match is None or not _WORKER_RE.search(match.group(2)):
            continue
        pid = int(match.group(1))
        if pid > 1 and pid not in process_seen_pids:
            process_seen_pids.add(pid)
            processes.append({"pid": pid})
    return tuple(processes)


_SERVICE_ROLES = MEMORY_REQUIRED_ROLES


def _compose_service_processes(project: str, role: str) -> tuple[dict[str, int | str], ...]:
    """Discover one compose service's process identity without mutating Docker.

    The performance run is allowed to inspect an already-running deployment,
    but it must not infer service memory from the load-generator process.  The
    container init PID is useful because its cgroup contains the whole service
    container; the cgroup sampler below reports the aggregate container peak.
    """

    docker = shutil.which("docker")
    if docker is None or role not in _SERVICE_ROLES:
        return ()
    try:
        listed = subprocess.run(  # noqa: S603 - fixed Docker executable/labels
            [
                docker,
                "ps",
                "--filter",
                f"label=com.docker.compose.project={project}",
                "--filter",
                f"label=com.docker.compose.service={role}",
                "--format",
                "{{.ID}}",
            ],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ()
    if listed.returncode != 0:
        return ()
    identities: list[dict[str, int | str]] = []
    seen: set[str] = set()
    for container_id in (line.strip() for line in listed.stdout.splitlines()):
        if not container_id or container_id in seen:
            continue
        seen.add(container_id)
        try:
            inspected = subprocess.run(  # noqa: S603 - ID came from Docker itself
                [docker, "inspect", "--format", "{{json .}}", container_id],
                cwd=ROOT,
                check=False,
                capture_output=True,
                text=True,
                timeout=10,
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        if inspected.returncode != 0:
            continue
        try:
            details = json.loads(inspected.stdout)
        except (TypeError, ValueError):
            continue
        if not isinstance(details, Mapping):
            continue
        state = details.get("State")
        config = details.get("Config")
        if not isinstance(state, Mapping) or not isinstance(config, Mapping):
            continue
        if state.get("Running") is not True:
            continue
        labels = config.get("Labels") or {}
        if not isinstance(labels, Mapping):
            continue
        try:
            pid = int(state.get("Pid", 0))
        except (TypeError, ValueError):
            continue
        inspected_id = details.get("Id")
        image_id = details.get("Image")
        if pid <= 1 or not isinstance(inspected_id, str) or not inspected_id:
            continue
        identity: dict[str, int | str] = {
            "role": role,
            "container_id": inspected_id,
            "pid": pid,
        }
        if isinstance(image_id, str) and image_id:
            identity["image_id"] = image_id
        source_value = labels.get(IMAGE_SOURCE_FINGERPRINT_LABEL)
        if isinstance(source_value, str) and source_value:
            identity["source_fingerprint"] = source_value
        identities.append(identity)
    return tuple(identities)


def _local_service_processes() -> dict[str, tuple[dict[str, int | str], ...]]:
    """Discover service roles from a local process table, read-only."""

    result: dict[str, list[dict[str, int | str]]] = {role: [] for role in _SERVICE_ROLES}
    ps = shutil.which("ps")
    if ps is None:
        return {role: tuple(items) for role, items in result.items()}
    try:
        completed = subprocess.run(  # noqa: S603 - fixed process inspection command
            [ps, "-eo", "pid=,args="],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return {role: tuple(items) for role, items in result.items()}
    if completed.returncode != 0:
        return {role: tuple(items) for role, items in result.items()}
    seen: set[tuple[str, int]] = set()
    role_pattern = re.compile(
        r"(?:trpc-service|trpc_service).*serve\s+--role\s+"
        r"(worker|outbox-dispatcher|channel-dispatcher|post-turn-projector)(?:\s|$)"
    )
    for line in completed.stdout.splitlines():
        match = re.match(r"\s*(\d+)\s+(.*)$", line)
        if match is None:
            continue
        try:
            pid = int(match.group(1))
        except ValueError:
            continue
        role_match = role_pattern.search(match.group(2))
        if role_match is None or pid <= 1:
            continue
        role = role_match.group(1)
        key = (role, pid)
        if key in seen:
            continue
        seen.add(key)
        result[role].append({"role": role, "pid": pid})
    return {role: tuple(items) for role, items in result.items()}


def _participating_processes(
    workers: Sequence[Mapping[str, Any]],
) -> dict[str, tuple[dict[str, int | str], ...]]:
    """Return the exact process/container set whose memory is production evidence."""

    result: dict[str, list[dict[str, int | str]]] = {role: [] for role in _SERVICE_ROLES}
    for worker in workers:
        item = dict(worker)
        item["role"] = "worker"
        result["worker"].append(cast(dict[str, int | str], item))
    real_project = os.getenv("TRPC_REAL_COMPOSE_PROJECT", "").strip()
    perf_project = os.getenv("TRPC_PERF_COMPOSE_PROJECT", "").strip()
    project = real_project or perf_project
    if project:
        for role in _SERVICE_ROLES[1:]:
            result[role].extend(_compose_service_processes(project, role))
    else:
        local = _local_service_processes()
        for role in _SERVICE_ROLES[1:]:
            result[role].extend(local[role])
    return {role: tuple(items) for role, items in result.items()}


def _read_numeric_file(path: Path) -> int | None:
    try:
        raw = path.read_text(encoding="ascii").strip()
    except (OSError, UnicodeError):
        return None
    if not raw or raw == "max":
        return None
    try:
        value = int(raw)
    except ValueError:
        return None
    return value if 0 <= value < 2**60 else None


def _proc_cgroup_memory_paths(pid: int) -> tuple[Path, ...]:
    """Resolve memory cgroup directories for a process without shelling out."""

    try:
        lines = Path(f"/proc/{pid}/cgroup").read_text(encoding="ascii").splitlines()
    except (OSError, UnicodeError):
        return ()
    paths: list[Path] = []
    for line in lines:
        parts = line.split(":", 2)
        if len(parts) != 3:
            continue
        hierarchy, controllers, relative = parts
        if hierarchy != "0" and "memory" not in controllers.split(","):
            continue
        relative_path = relative.lstrip("/")
        roots = [Path("/sys/fs/cgroup")]
        if hierarchy != "0":
            roots.append(Path("/sys/fs/cgroup/memory"))
        for root in roots:
            candidate = root / relative_path
            if candidate not in paths:
                paths.append(candidate)
    return tuple(paths)


def _process_memory_snapshot(pid: int) -> dict[str, int | str | None]:
    """Read RSS high-water and cgroup peak values for one process."""

    snapshot: dict[str, int | str | None] = {
        "pid": pid,
        "rss_bytes": None,
        "rss_peak_bytes": None,
        "cgroup_current_bytes": None,
        "cgroup_peak_bytes": None,
        "cgroup_limit_bytes": None,
        "cgroup_key": None,
    }
    try:
        lines = Path(f"/proc/{pid}/status").read_text(encoding="ascii").splitlines()
    except (OSError, UnicodeError):
        lines = []
    values: dict[str, int] = {}
    for line in lines:
        name, separator, raw = line.partition(":")
        if separator and name in {"VmRSS", "VmHWM"}:
            pieces = raw.strip().split()
            if pieces:
                try:
                    multiplier = 1024 if len(pieces) == 1 or pieces[1] == "kB" else 1
                    values[name] = int(pieces[0]) * multiplier
                except ValueError:
                    pass
    snapshot["rss_bytes"] = values.get("VmRSS")
    snapshot["rss_peak_bytes"] = values.get("VmHWM")
    for cgroup in _proc_cgroup_memory_paths(pid):
        current = _read_numeric_file(cgroup / "memory.current")
        peak = _read_numeric_file(cgroup / "memory.peak")
        limit = _read_numeric_file(cgroup / "memory.max")
        if current is None and peak is None and limit is None:
            current = _read_numeric_file(cgroup / "memory.usage_in_bytes")
            peak = _read_numeric_file(cgroup / "memory.max_usage_in_bytes")
            limit = _read_numeric_file(cgroup / "memory.limit_in_bytes")
        if current is not None or peak is not None or limit is not None:
            snapshot.update(
                {
                    "cgroup_current_bytes": current,
                    "cgroup_peak_bytes": peak,
                    "cgroup_limit_bytes": limit,
                    "cgroup_key": str(cgroup),
                }
            )
            break
    return snapshot


def _container_memory_snapshot(container_id: str) -> dict[str, int | str | None]:
    """Read kernel peak counters from inside a Docker container.

    Docker Desktop exposes Linux container PIDs that are not addressable via
    the Windows host's ``/proc``.  The fallback is still kernel evidence: it
    reads PID 1's VmHWM and the container's memory cgroup files without
    changing the container or relying on ``docker stats`` estimates.
    """

    snapshot: dict[str, int | str | None] = {
        "container_id": container_id,
        "rss_bytes": None,
        "rss_peak_bytes": None,
        "cgroup_current_bytes": None,
        "cgroup_peak_bytes": None,
        "cgroup_limit_bytes": None,
        "cgroup_key": None,
        "sampling_source": "container_procfs",
    }
    if re.fullmatch(r"[0-9a-f]{12,64}", container_id) is None:
        return snapshot
    docker = shutil.which("docker")
    if docker is None:
        return snapshot
    probe = (
        'awk \'/^(VmRSS|VmHWM):/ {gsub(":", "", $1); '
        'print $1 "=" $2}\' /proc/1/status 2>/dev/null; '
        "for f in memory.current memory.peak memory.max memory.usage_in_bytes "
        "memory.max_usage_in_bytes memory.limit_in_bytes; do "
        "for root in /sys/fs/cgroup /sys/fs/cgroup/memory; do "
        'p="$root/$f"; if [ -r "$p" ]; then printf \'%s=\' "$f"; '
        'cat "$p"; break; fi; done; done'
    )
    try:
        completed = subprocess.run(  # noqa: S603 - fixed read-only Docker probe
            [docker, "exec", container_id, "sh", "-c", probe],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return snapshot
    if completed.returncode != 0:
        return snapshot
    values: dict[str, int] = {}
    for line in completed.stdout.splitlines():
        name, separator, raw = line.partition("=")
        if not separator or raw.strip() == "max":
            continue
        try:
            value = int(raw.strip().split()[0])
        except (IndexError, ValueError):
            continue
        if name in {"VmRSS", "VmHWM"}:
            value *= 1024
        if 0 <= value < 2**60:
            values[name] = value
    snapshot.update(
        {
            "rss_bytes": values.get("VmRSS"),
            "rss_peak_bytes": values.get("VmHWM"),
            "cgroup_current_bytes": values.get("memory.current")
            or values.get("memory.usage_in_bytes"),
            "cgroup_peak_bytes": values.get("memory.peak")
            or values.get("memory.max_usage_in_bytes"),
            "cgroup_limit_bytes": values.get("memory.max") or values.get("memory.limit_in_bytes"),
            "cgroup_key": f"docker:{container_id}",
        }
    )
    return snapshot


def _memory_observation(
    participating: Mapping[str, Sequence[Mapping[str, Any]]],
    *,
    resources: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Build bounded, production-safe memory evidence from real identities.

    ``VmHWM`` is the kernel-maintained RSS high-water mark.  Where a process
    belongs to a memory cgroup, the cgroup peak is preferred and deduplicated
    by cgroup path so multiple roles in one cgroup cannot inflate the total.
    Missing observations are never replaced with estimates; the result is
    explicitly ``not_run`` and the release gate must refuse promotion.
    """

    started_at = datetime.now(UTC).isoformat().replace("+00:00", "Z")
    total = sum(len(participating.get(role, ())) for role in _SERVICE_ROLES)
    if total == 0 or total > MEMORY_MAX_IDENTITIES:
        return {
            "status": "not_run",
            "reason": "participating memory identities are missing or exceed the safety bound",
            "required_roles": list(_SERVICE_ROLES),
            "observed_at": started_at,
            "coverage_complete": False,
        }
    role_observations: dict[str, Any] = {}
    all_observed = True
    records: list[dict[str, Any]] = []
    for role in _SERVICE_ROLES:
        identities = participating.get(role, ())
        role_records: list[dict[str, Any]] = []
        for identity in identities:
            pid = identity.get("pid")
            if isinstance(pid, bool) or not isinstance(pid, int) or pid <= 1:
                all_observed = False
                continue
            sample = _process_memory_snapshot(pid)
            container_id = identity.get("container_id")
            if (
                not isinstance(sample.get("rss_peak_bytes"), int)
                and not isinstance(sample.get("cgroup_peak_bytes"), int)
                and isinstance(container_id, str)
            ):
                sample = _container_memory_snapshot(container_id)
            rss_peak = sample.get("rss_peak_bytes")
            cgroup_peak = sample.get("cgroup_peak_bytes")
            if not isinstance(rss_peak, int) and not isinstance(cgroup_peak, int):
                all_observed = False
            record = {
                "role": role,
                "pid": pid,
                "container_id": identity.get("container_id"),
                "rss_peak_bytes": rss_peak,
                "cgroup_peak_bytes": cgroup_peak,
                "cgroup_current_bytes": sample.get("cgroup_current_bytes"),
                "cgroup_limit_bytes": sample.get("cgroup_limit_bytes"),
                "cgroup_key": sample.get("cgroup_key"),
                "sampling_source": sample.get("sampling_source", "host_procfs"),
            }
            role_records.append(record)
            records.append(record)
        role_observations[role] = {
            "identity_count": len(identities),
            "observed_count": len(role_records),
            "observations": role_records,
        }
        if not identities or len(role_records) != len(identities):
            all_observed = False
    cgroup_records = [item for item in records if isinstance(item.get("cgroup_key"), str)]
    unique_cgroups: dict[str, dict[str, Any]] = {}
    for item in cgroup_records:
        key = cast(str, item["cgroup_key"])
        unique_cgroups[key] = item
    cgroup_peak = sum(
        int(item["cgroup_peak_bytes"])
        for item in unique_cgroups.values()
        if isinstance(item.get("cgroup_peak_bytes"), int)
    )
    rss_peak = sum(
        int(item["rss_peak_bytes"])
        for item in records
        if isinstance(item.get("rss_peak_bytes"), int)
    )
    cgroup_limit = sum(
        int(item["cgroup_limit_bytes"])
        for item in unique_cgroups.values()
        if isinstance(item.get("cgroup_limit_bytes"), int) and int(item["cgroup_limit_bytes"]) > 0
    )
    peak_bytes = cgroup_peak if cgroup_peak > 0 else rss_peak
    resource_limit = resources.get("available_memory_bytes") if resources else None
    threshold = cgroup_limit if cgroup_limit > 0 else resource_limit
    within_limit = isinstance(threshold, int) and threshold > 0 and peak_bytes <= threshold
    status = "pass" if all_observed and within_limit else ("fail" if all_observed else "not_run")
    reason = None
    if not all_observed:
        reason = "one or more participating service identities lack real RSS/cgroup peak evidence"
    elif not within_limit:
        reason = "observed memory peak exceeds the measured safety threshold"
    return {
        "status": status,
        "sampling_method": "kernel_peak_counters",
        "sample_count": 1,
        "sampling_interval_seconds": MEMORY_SAMPLE_INTERVAL_SECONDS,
        "required_roles": list(_SERVICE_ROLES),
        "role_observations": role_observations,
        "coverage_complete": all_observed,
        "observed_identity_count": len(records),
        "cgroup_identity_count": len(cgroup_records),
        "cgroup_scope_count": len(unique_cgroups),
        "peak_rss_bytes": rss_peak if rss_peak > 0 else None,
        "peak_cgroup_bytes": cgroup_peak if cgroup_peak > 0 else None,
        "peak_bytes": peak_bytes if peak_bytes > 0 else None,
        "safety_threshold_bytes": threshold,
        "threshold_source": "cgroup_limit" if cgroup_limit > 0 else "available_memory",
        "within_safety_threshold": within_limit,
        "observed_at": started_at,
        **({"reason": reason} if reason else {}),
    }


def _available_memory_bytes() -> int | None:
    """Return available memory without importing a process-management package."""

    if os.name == "nt":

        class MemoryStatus(ctypes.Structure):
            _fields_ = [
                ("length", ctypes.c_ulong),
                ("memory_load", ctypes.c_ulong),
                ("total_physical", ctypes.c_ulonglong),
                ("available_physical", ctypes.c_ulonglong),
                ("total_page_file", ctypes.c_ulonglong),
                ("available_page_file", ctypes.c_ulonglong),
                ("total_virtual", ctypes.c_ulonglong),
                ("available_virtual", ctypes.c_ulonglong),
                ("available_extended_virtual", ctypes.c_ulonglong),
            ]

        status = MemoryStatus()
        status.length = ctypes.sizeof(MemoryStatus)
        try:
            if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(status)):
                return int(status.available_physical)
        except (AttributeError, OSError):
            return None
        return None

    meminfo = Path("/proc/meminfo")
    if not meminfo.exists():
        return None
    try:
        for line in meminfo.read_text(encoding="ascii").splitlines():
            name, _, raw_value = line.partition(":")
            if name.strip() == "MemAvailable":
                value, _, unit = raw_value.strip().partition(" ")
                multiplier = 1024 if unit.lower() == "kb" else 1
                return int(value) * multiplier
    except (OSError, ValueError):
        return None
    return None


def _cgroup_value(path: Path) -> int | None:
    """Read one Linux cgroup numeric value without trusting ``max``."""

    try:
        raw = path.read_text(encoding="ascii").strip()
    except (OSError, UnicodeError):
        return None
    if not raw or raw == "max":
        return None
    try:
        value = int(raw)
    except ValueError:
        return None
    # v1 uses an effectively-infinite sentinel on some hosts.  Treat it as
    # unlimited rather than accidentally making the preflight unusable.
    return value if 0 < value < 2**60 else None


def _cgroup_memory_limit_bytes() -> int | None:
    """Return the current cgroup memory limit when one is enforceable."""

    for path in (
        Path("/sys/fs/cgroup/memory.max"),
        Path("/sys/fs/cgroup/memory/memory.limit_in_bytes"),
    ):
        value = _cgroup_value(path)
        if value is not None:
            return value
    return None


def _cgroup_memory_current_bytes() -> int | None:
    """Return current cgroup memory usage, if the kernel exposes it."""

    for path in (
        Path("/sys/fs/cgroup/memory.current"),
        Path("/sys/fs/cgroup/memory/memory.usage_in_bytes"),
    ):
        value = _cgroup_value(path)
        if value is not None:
            return value
    return None


def _cgroup_cpu_quota_count() -> int | None:
    """Return the integer CPU capacity imposed by cgroup v2/v1."""

    try:
        raw = Path("/sys/fs/cgroup/cpu.max").read_text(encoding="ascii").split()
        if len(raw) >= 2 and raw[0] != "max":
            quota, period = int(raw[0]), int(raw[1])
            if quota > 0 and period > 0:
                return max(1, math.floor(quota / period))
    except (OSError, UnicodeError, ValueError):
        pass
    try:
        quota = int(Path("/sys/fs/cgroup/cpu/cpu.cfs_quota_us").read_text(encoding="ascii"))
        period = int(Path("/sys/fs/cgroup/cpu/cpu.cfs_period_us").read_text(encoding="ascii"))
        if quota > 0 and period > 0:
            return max(1, math.floor(quota / period))
    except (OSError, UnicodeError, ValueError):
        return None
    return None


def _resource_snapshot() -> dict[str, int | None]:
    host_cpu_count = int(os.cpu_count() or 0)
    cpu_quota_count = _cgroup_cpu_quota_count()
    cpu_count = (
        min(host_cpu_count, cpu_quota_count)
        if cpu_quota_count is not None and host_cpu_count
        else cpu_quota_count or host_cpu_count
    )
    host_available = _available_memory_bytes()
    memory_limit = _cgroup_memory_limit_bytes()
    memory_current = _cgroup_memory_current_bytes()
    cgroup_available = None
    if memory_limit is not None and memory_current is not None:
        cgroup_available = max(0, memory_limit - memory_current)
    available = host_available
    if memory_limit is not None and memory_current is None:
        # A known hard limit with an unreadable usage counter cannot be
        # converted into a safe free-memory estimate.  Do not fall back to
        # host-wide memory, which may greatly overstate the container budget.
        available = None
    elif cgroup_available is not None:
        available = cgroup_available if available is None else min(available, cgroup_available)
    return {
        "cpu_count": cpu_count,
        "host_cpu_count": host_cpu_count,
        "cpu_quota_count": cpu_quota_count,
        "available_memory_bytes": available,
        "host_available_memory_bytes": host_available,
        "cgroup_memory_limit_bytes": memory_limit,
        "cgroup_memory_current_bytes": memory_current,
        "cgroup_available_memory_bytes": cgroup_available,
    }


def _estimated_runtime_connections(*, min_workers: int, db_pool_size: int) -> int:
    """Estimate the fixed performance topology's simultaneous DB sessions."""

    return (
        GATEWAY_POOL_MAX_SIZE
        + (max(0, min_workers) * WORKER_POOL_MAX_SIZE)
        + OUTBOX_POOL_MAX_SIZE
        + RECOVERY_POOL_MAX_SIZE
        + max(0, db_pool_size)
        + PROBE_CONNECTION_HEADROOM
    )


def _required_memory_bytes(
    *,
    db_pool_size: int,
    max_inflight: int,
    burst_turns: int,
) -> int:
    """Calculate a bounded, conservative memory floor for the load process.

    The two-GiB base reserves room for the service and its databases.  The
    parameter increments are intentionally coarse upper-bound estimates; the
    final increment is capped so malformed or unusually large inputs cannot
    turn this calculation into an unbounded resource request.
    """

    increment = (
        max(0, db_pool_size) * MEMORY_PER_DB_POOL_CONNECTION_BYTES
        + max(0, max_inflight) * MEMORY_PER_INFLIGHT_REQUEST_BYTES
        + max(0, burst_turns) * MEMORY_PER_BURST_TURN_BYTES
    )
    return MIN_AVAILABLE_MEMORY_BYTES + min(
        increment,
        MAX_DYNAMIC_MEMORY_INCREMENT_BYTES,
    )


def _live_opt_in(args: argparse.Namespace, *, require_worker: bool = False) -> bool:
    """Require independent CLI, environment, and (for workers) capability opt-ins."""

    if not bool(getattr(args, "execute", False)):
        return False
    if not bool(getattr(args, "confirm_real_load", False)):
        return False
    if os.getenv(OPT_IN) != "1":
        return False
    if os.getenv(CONFIRM_REAL_LOAD_ENV) != CONFIRM_REAL_LOAD_VALUE:
        return False
    return not require_worker or bool(os.getenv(WORKER_TOKEN_ENV))


def _opt_in_reasons(args: argparse.Namespace, *, require_worker: bool = False) -> list[str]:
    reasons: list[str] = []
    if not bool(getattr(args, "execute", False)):
        reasons.append("--execute is required")
    if os.getenv(OPT_IN) != "1":
        reasons.append(f"{OPT_IN}=1 is required")
    if not bool(getattr(args, "confirm_real_load", False)):
        reasons.append("--confirm-real-load is required for the dedicated live-load command")
    if os.getenv(CONFIRM_REAL_LOAD_ENV) != CONFIRM_REAL_LOAD_VALUE:
        reasons.append(f"{CONFIRM_REAL_LOAD_ENV}={CONFIRM_REAL_LOAD_VALUE} is required")
    if require_worker and not os.getenv(WORKER_TOKEN_ENV):
        reasons.append("load worker capability token is missing")
    return reasons


def _hard_process_timeout(args: argparse.Namespace) -> float:
    configured = float(getattr(args, "timeout_seconds", DEFAULT_TIMEOUT_SECONDS))
    if not math.isfinite(configured) or configured <= 0:
        return 0.0
    return min(
        MAX_LOAD_PROCESS_TIMEOUT_SECONDS,
        max(30.0, (configured * 3.0) + 30.0),
    )


def _preflight(args: argparse.Namespace) -> dict[str, Any]:
    callbacks = int(args.callbacks)
    burst_turns = int(args.burst_turns)
    callback_rate = float(args.callback_rate)
    min_workers = int(args.min_workers)
    db_pool_size = int(args.db_pool_size)
    max_inflight = int(getattr(args, "max_inflight", DEFAULT_MAX_INFLIGHT))
    timeout_seconds = float(args.timeout_seconds)
    if callbacks < 1 or burst_turns < 1:
        return {"status": "fail", "reason": "callback and burst counts must be positive"}
    if callbacks > MAX_CALLBACKS:
        return {
            "status": "fail",
            "reason": f"callback count exceeds safety limit {MAX_CALLBACKS}",
        }
    if burst_turns > MAX_BURST_TURNS:
        return {
            "status": "fail",
            "reason": f"burst turn count exceeds safety limit {MAX_BURST_TURNS}",
        }
    if not math.isfinite(callback_rate) or callback_rate <= 0:
        return {"status": "fail", "reason": "callback rate must be finite and positive"}
    if callback_rate > MAX_CALLBACK_RATE:
        return {
            "status": "fail",
            "reason": f"callback rate exceeds safety limit {MAX_CALLBACK_RATE:g}",
        }
    if min_workers < 2:
        return {"status": "fail", "reason": "at least two independent workers are required"}
    if min_workers > MAX_MIN_WORKERS:
        return {
            "status": "fail",
            "reason": f"worker count exceeds safety limit {MAX_MIN_WORKERS}",
        }
    if db_pool_size < 2:
        return {"status": "fail", "reason": "database pool and timeout must be positive"}
    if db_pool_size > MAX_DB_POOL_SIZE:
        return {
            "status": "fail",
            "reason": f"database pool size exceeds safety limit {MAX_DB_POOL_SIZE}",
        }
    if max_inflight < 1 or max_inflight > MAX_INFLIGHT:
        return {
            "status": "fail",
            "reason": f"in-flight limit exceeds safety limit {MAX_INFLIGHT}",
        }
    if db_pool_size > max_inflight:
        return {
            "status": "fail",
            "reason": "database pool size must not exceed the in-flight limit",
        }
    if not math.isfinite(timeout_seconds) or timeout_seconds <= 0:
        return {
            "status": "fail",
            "reason": "timeout must be finite and positive",
        }
    if timeout_seconds > MAX_TIMEOUT_SECONDS:
        return {
            "status": "fail",
            "reason": f"timeout exceeds safety limit {MAX_TIMEOUT_SECONDS:g}s",
        }
    required_memory_bytes = _required_memory_bytes(
        db_pool_size=db_pool_size,
        max_inflight=max_inflight,
        burst_turns=burst_turns,
    )
    resources = _resource_snapshot()
    resources["required_memory_bytes"] = required_memory_bytes
    estimated_connections = _estimated_runtime_connections(
        min_workers=min_workers,
        db_pool_size=db_pool_size,
    )
    resources["estimated_runtime_connections"] = estimated_connections
    resources["max_estimated_runtime_connections"] = MAX_ESTIMATED_RUNTIME_CONNECTIONS
    if estimated_connections > MAX_ESTIMATED_RUNTIME_CONNECTIONS:
        return {
            "status": "not_run",
            "reason": (
                "estimated runtime PostgreSQL connections exceed the safety budget "
                f"of {MAX_ESTIMATED_RUNTIME_CONNECTIONS}"
            ),
            "resources": resources,
        }
    cpu_count = int(resources["cpu_count"] or 0)
    if cpu_count < min_workers:
        return {
            "status": "not_run",
            "reason": f"need at least {min_workers} CPUs, found {cpu_count}",
            "resources": resources,
        }
    available_memory = resources["available_memory_bytes"]
    if available_memory is None:
        return {
            "status": "not_run",
            "reason": "available memory could not be determined safely",
            "resources": resources,
        }
    if available_memory < required_memory_bytes:
        return {
            "status": "not_run",
            "reason": (
                "available memory is below the required performance safety threshold "
                f"of {required_memory_bytes} bytes"
            ),
            "resources": resources,
        }
    workers = _worker_processes()
    if len(workers) < min_workers:
        return {
            "status": "not_run",
            "reason": f"need {min_workers} independent worker processes, found {len(workers)}",
            "worker_processes": workers,
            "resources": resources,
        }
    actual_estimated_connections = _estimated_runtime_connections(
        min_workers=len(workers),
        db_pool_size=db_pool_size,
    )
    resources["estimated_runtime_connections"] = actual_estimated_connections
    if actual_estimated_connections > MAX_ESTIMATED_RUNTIME_CONNECTIONS:
        return {
            "status": "not_run",
            "reason": (
                "discovered runtime PostgreSQL connections exceed the safety budget "
                f"of {MAX_ESTIMATED_RUNTIME_CONNECTIONS}"
            ),
            "worker_processes": workers,
            "resources": resources,
        }
    source = _source_fingerprint()
    image_attestation = _worker_image_attestation(workers, source)
    participating = _participating_processes(workers)
    memory_observation = _memory_observation(participating, resources=resources)
    return {
        "status": "pass",
        "worker_processes": workers,
        "participating_processes": participating,
        "memory_observation": memory_observation,
        "resources": resources,
        "source_fingerprint": source,
        "worker_image_attestation": image_attestation,
    }


def _connection_dsn(raw: str) -> str:
    return raw.replace("postgresql+asyncpg://", "postgresql://")


def _session_hmac_key_bytes(value: str) -> bytes:
    """Decode the session key with the same contract used by service roles.

    The service accepts an unpadded base64url/base64 value when it decodes to
    at least 32 bytes, and otherwise falls back to the raw UTF-8 value when it
    itself is at least 32 bytes.  Keeping this small pure helper local avoids
    importing CLI startup code into the acceptance gate.
    """

    raw = value.encode()
    for decoder in (base64.urlsafe_b64decode, base64.b64decode):
        try:
            candidate = decoder(value + "=" * (-len(value) % 4))
        except ValueError:
            continue
        if len(candidate) >= 32:
            return candidate
    if len(raw) < 32:
        raise ValueError("TRPC_REAL_SESSION_HMAC_KEY must decode to at least 32 bytes")
    return raw


