class _PerformanceArgumentParser(argparse.ArgumentParser):
    """Normalize the transport defaults without hiding invalid combinations."""

    @overload
    def parse_args(
        self,
        args: Sequence[str] | None = None,
        namespace: None = None,
    ) -> argparse.Namespace: ...

    @overload
    def parse_args(
        self,
        args: Sequence[str] | None,
        namespace: _ParserNamespace,
    ) -> _ParserNamespace: ...

    @overload
    def parse_args(self, *, namespace: _ParserNamespace) -> _ParserNamespace: ...

    def parse_args(
        self,
        args: Sequence[str] | None = None,
        namespace: Any = None,
    ) -> Any:
        parsed = super().parse_args(args, namespace)
        try:
            _apply_scheduler_transport(parsed)
        except ValueError:
            # Keep parsing successful so ``main`` can write its normal
            # report-safe, fail-closed result for a cross-wired invocation.
            pass
        return parsed


