async def _scoped_fetch(
    pool: asyncpg.Pool,
    tenant_id: str,
    query: str,
    *args: Any,
) -> list[asyncpg.Record]:
    async with pool.acquire() as connection, connection.transaction():
        await connection.execute("SELECT set_config('app.tenant_id', $1, true)", tenant_id)
        return list(await connection.fetch(query, *args))


def _loopback_gateway_metadata(base_url: str) -> dict[str, Any]:
    """Validate the performance gateway and return only safe endpoint metadata.

    The real acceptance load is deliberately restricted to a gateway bound on
    the local machine.  This prevents an accidental environment value from
    turning the acceptance script into a provider or third-party load tool.
    The returned object never contains the URL itself.
    """

    try:
        parsed = urlsplit(base_url)
    except ValueError:
        raise ValueError("performance gateway URL is invalid") from None
    host = (parsed.hostname or "").lower()
    if parsed.scheme not in {"http", "https"} or host not in {
        "localhost",
        "127.0.0.1",
        "::1",
    }:
        raise ValueError("performance gateway must use localhost, 127.0.0.1, or ::1")
    if parsed.query or parsed.fragment or parsed.username or parsed.password:
        raise ValueError("performance gateway URL must not contain query or credentials")
    try:
        port = parsed.port
    except ValueError:
        raise ValueError("performance gateway URL has an invalid port") from None
    return {
        "scheme": parsed.scheme,
        "host_class": "loopback",
        "port": port or (443 if parsed.scheme == "https" else 80),
        "path_present": bool(parsed.path.rstrip("/")),
    }


async def _lookup_authoritative_inbound_batch(
    pool: asyncpg.Pool,
    tenant_id: str,
    route: BindingRoute,
    external_message_ids: Sequence[str],
) -> dict[str, Any]:
    """Resolve HTTP-accepted IDs through the tenant-scoped PostgreSQL log.

    The gateway acknowledgement only proves that the callback was accepted by
    HTTP.  The durable IDs used by ``_wait_for_batch`` must come from the
    authoritative ``inbound_messages`` rows, with every tenant/channel/account
    predicate present in the query.  Any missing or duplicate row fails closed.
    """

    expected = tuple(str(item) for item in external_message_ids)
    if len(expected) != len(set(expected)):
        return {
            "status": "fail",
            "reason": "HTTP accepted external message IDs are duplicated",
            "requested_count": len(expected),
            "row_count": 0,
            "missing_count": 0,
            "duplicate_count": len(expected) - len(set(expected)),
            "inbound_ids": (),
            "session_ids": (),
        }
    if not expected:
        return {
            "status": "fail",
            "reason": "HTTP phase did not return accepted external message IDs",
            "requested_count": 0,
            "row_count": 0,
            "missing_count": 0,
            "duplicate_count": 0,
            "inbound_ids": (),
            "session_ids": (),
        }

    channel_value = getattr(route.binding.channel, "value", route.binding.channel)
    account_id = str(route.binding.account_id)
    rows = await _scoped_fetch(
        pool,
        tenant_id,
        """
        SELECT inbound_id, session_id, channel, account_id, external_message_id
          FROM inbound_messages
         WHERE tenant_id=$1 AND channel=$2 AND account_id=$3
           AND external_message_id=ANY($4::text[])
        """,
        tenant_id,
        str(channel_value),
        account_id,
        list(expected),
    )

    by_external: dict[str, tuple[str, str]] = {}
    duplicate_count = 0
    invalid_count = 0
    for row in rows:
        external_id = row["external_message_id"]
        row_channel = row["channel"]
        row_account = row["account_id"]
        inbound_id = row["inbound_id"]
        session_id = row["session_id"]
        if (
            not isinstance(external_id, str)
            or row_channel != str(channel_value)
            or row_account != account_id
            or inbound_id is None
            or session_id is None
        ):
            invalid_count += 1
            continue
        if external_id in by_external:
            duplicate_count += 1
            continue
        by_external[external_id] = (str(inbound_id), str(session_id))

    missing = [external_id for external_id in expected if external_id not in by_external]
    if duplicate_count or invalid_count or missing or len(rows) != len(expected):
        return {
            "status": "fail",
            "reason": "authoritative inbound lookup was incomplete or duplicated",
            "requested_count": len(expected),
            "row_count": len(rows),
            "missing_count": len(missing),
            "duplicate_count": duplicate_count,
            "invalid_count": invalid_count,
            "inbound_ids": (),
            "session_ids": (),
        }

    ordered = [by_external[external_id] for external_id in expected]
    inbound_ids = tuple(item[0] for item in ordered)
    session_ids = tuple(item[1] for item in ordered)
    if len(inbound_ids) != len(set(inbound_ids)) or len(session_ids) != len(set(session_ids)):
        return {
            "status": "fail",
            "reason": "authoritative inbound lookup returned duplicate durable IDs",
            "requested_count": len(expected),
            "row_count": len(rows),
            "missing_count": 0,
            "duplicate_count": 0,
            "inbound_ids": (),
            "session_ids": (),
        }
    return {
        "status": "pass",
        "requested_count": len(expected),
        "row_count": len(rows),
        "missing_count": 0,
        "duplicate_count": 0,
        "inbound_ids": inbound_ids,
        "session_ids": session_ids,
    }


async def _redis_pending(
    redis: Any,
    *,
    stream: str,
    group: str,
) -> dict[str, int]:
    summary = await redis.execute_command("XPENDING", stream, group)
    pending = _redis_pending_count(summary)
    return {"pending": pending, "stream_length": int(await redis.xlen(stream))}


def _redis_pending_count(summary: Any) -> int:
    """Normalize RESP2 list and RESP3/redis-py mapping XPENDING summaries."""

    if not summary:
        return 0
    if isinstance(summary, dict):
        value = summary.get("pending", summary.get(b"pending", 0))
        if value is None:
            return 0
        return int(value)
    return int(summary[0])


async def _batch_state(
    pool: asyncpg.Pool,
    tenant_id: str,
    inbound_ids: Sequence[str],
    session_ids: Sequence[str],
    *,
    scheduler_version: SchedulerVersion = SchedulerVersion.V1,
) -> dict[str, Any]:
    if not inbound_ids:
        return {
            "inbound_statuses": {},
            "turn_statuses": {},
            "published_inbound_outbox": 0,
            "published_scheduler_outbox": 0,
            "scheduler_version": scheduler_version.value,
            "leased_sessions": 0,
            "mailbox_expected_count": 0,
            "mailbox_row_count": 0,
            "mailbox_idle_count": 0,
            "mailbox_settled_count": 0,
            "mailbox_unresolved_item_count": 0,
            "turns": (),
        }
    inbound_uuids = [UUID(item) for item in inbound_ids]
    inbound_rows = await _scoped_fetch(
        pool,
        tenant_id,
        """
        SELECT status,count(*)::bigint AS count
          FROM inbound_messages
         WHERE tenant_id=$1 AND inbound_id=ANY($2::uuid[])
         GROUP BY status
        """,
        tenant_id,
        inbound_uuids,
    )
    turn_rows = await _scoped_fetch(
        pool,
        tenant_id,
        """
        SELECT normalized_status AS status,count(*)::bigint AS count
          FROM (
                SELECT CASE
                           WHEN status='committed' AND committed_at IS NULL
                               THEN 'committed_missing_timestamp'
                           ELSE status
                       END AS normalized_status
                  FROM session_turns
                 WHERE tenant_id=$1 AND inbound_id=ANY($2::uuid[])
               ) AS normalized_turns
         GROUP BY normalized_status
        """,
        tenant_id,
        inbound_uuids,
    )
    if scheduler_version == SchedulerVersion.V2:
        published = await _scoped_fetch(
            pool,
            tenant_id,
            """
            SELECT count(*)::bigint
              FROM outbox_events
             WHERE tenant_id=$1 AND aggregate_type='session'
               AND event_type='session.ready.v2'
               AND aggregate_id=ANY($2::text[]) AND published_at IS NOT NULL
            """,
            tenant_id,
            list(dict.fromkeys(session_ids)),
        )
    else:
        published = await _scoped_fetch(
            pool,
            tenant_id,
            """
            SELECT count(*)::bigint
              FROM outbox_events
             WHERE tenant_id=$1 AND aggregate_type='inbound'
               AND aggregate_id=ANY($2::text[]) AND published_at IS NOT NULL
            """,
            tenant_id,
            list(inbound_ids),
        )
    leased = await _scoped_fetch(
        pool,
        tenant_id,
        """
        SELECT count(*)::bigint
          FROM sessions
         WHERE tenant_id=$1 AND session_id=ANY($2::text[])
           AND lease_owner IS NOT NULL
        """,
        tenant_id,
        list(session_ids),
    )
    mailbox_expected_count = (
        len(set(session_ids)) if scheduler_version == SchedulerVersion.V2 else 0
    )
    mailbox_row_count = 0
    mailbox_idle_count = 0
    mailbox_settled_count = 0
    mailbox_unresolved_item_count = 0
    if scheduler_version == SchedulerVersion.V2 and mailbox_expected_count:
        mailbox_rows = await _scoped_fetch(
            pool,
            tenant_id,
            """
            SELECT count(*)::bigint AS row_count,
                   count(*) FILTER (WHERE status='IDLE')::bigint AS idle_count,
                   count(*) FILTER (
                       WHERE status='IDLE'
                         AND accepted_sequence=resolved_sequence
                         AND processing_sequence IS NULL
                         AND processing_inbound_id IS NULL
                         AND lease_owner IS NULL
                         AND lease_expires_at IS NULL
                         AND retry_at IS NULL
                   )::bigint AS settled_count,
                   (
                       SELECT count(*)::bigint
                         FROM session_mailbox_items AS i
                        WHERE i.tenant_id=$1
                          AND i.session_id=ANY($2::text[])
                          AND i.resolved_at IS NULL
                   ) AS unresolved_item_count
              FROM session_mailboxes
             WHERE tenant_id=$1 AND session_id=ANY($2::text[])
            """,
            tenant_id,
            list(dict.fromkeys(session_ids)),
        )
        if mailbox_rows:
            mailbox_row = mailbox_rows[0]
            mailbox_row_count = int(mailbox_row["row_count"])
            mailbox_idle_count = int(mailbox_row["idle_count"])
            mailbox_settled_count = int(mailbox_row["settled_count"])
            mailbox_unresolved_item_count = int(mailbox_row["unresolved_item_count"])
    turns = await _scoped_fetch(
        pool,
        tenant_id,
        """
        SELECT started_at,committed_at
          FROM session_turns
         WHERE tenant_id=$1 AND inbound_id=ANY($2::uuid[])
           AND status='committed' AND committed_at IS NOT NULL
        """,
        tenant_id,
        inbound_uuids,
    )
    published_count = int(published[0][0]) if published else 0
    return {
        "inbound_statuses": {str(row["status"]): int(row["count"]) for row in inbound_rows},
        "turn_statuses": {str(row["status"]): int(row["count"]) for row in turn_rows},
        # Keep the legacy key for existing report readers while exposing the
        # scheduler-neutral name. In v2 this count represents published
        # session.ready.v2 wakeups, not inbound.accepted events.
        "published_inbound_outbox": published_count,
        "published_scheduler_outbox": published_count,
        "scheduler_version": scheduler_version.value,
        "leased_sessions": int(leased[0][0]) if leased else 0,
        "mailbox_expected_count": mailbox_expected_count,
        "mailbox_row_count": mailbox_row_count,
        "mailbox_idle_count": mailbox_idle_count,
        "mailbox_settled_count": mailbox_settled_count,
        "mailbox_unresolved_item_count": mailbox_unresolved_item_count,
        "turns": tuple((row["started_at"], row["committed_at"]) for row in turns),
    }


def _max_overlap(turns: Iterable[tuple[Any, Any]]) -> int:
    def timestamp(value: Any) -> float:
        return float(value.timestamp()) if hasattr(value, "timestamp") else float(value)

    points: list[tuple[float, int]] = []
    for started, committed in turns:
        if started is None or committed is None:
            continue
        start = timestamp(started)
        end = timestamp(committed)
        if end < start:
            continue
        points.extend(((start, 1), (end, -1)))
    active = 0
    maximum = 0
    for _, delta in sorted(points, key=lambda item: (item[0], item[1])):
        active += delta
        maximum = max(maximum, active)
    return maximum


async def _wait_for_batch(
    pool: asyncpg.Pool,
    redis: Any,
    *,
    tenant_id: str,
    inbound_ids: Sequence[str],
    session_ids: Sequence[str],
    baseline_pending: int,
    stream: str,
    group: str,
    wait_seconds: float,
    scheduler_version: SchedulerVersion = SchedulerVersion.V1,
) -> dict[str, Any]:
    expected = len(inbound_ids)
    expected_outbox = (
        len(set(session_ids)) if scheduler_version == SchedulerVersion.V2 else expected
    )
    if wait_seconds <= 0 or wait_seconds > MAX_TIMEOUT_SECONDS:
        return {
            "status": "fail",
            "reason": "batch wait timeout is outside the safety bounds",
            "state": {},
            "redis": None,
        }
    deadline = time.monotonic() + wait_seconds
    latest: dict[str, Any] = {}
    latest_redis: dict[str, int] | None = None
    redis_failure: dict[str, str] | None = None
    postgres_failure: dict[str, str] | None = None
    while time.monotonic() < deadline:
        try:
            remaining = max(0.01, deadline - time.monotonic())
            latest, latest_redis = await asyncio.wait_for(
                asyncio.gather(
                    _batch_state(
                        pool,
                        tenant_id,
                        inbound_ids,
                        session_ids,
                        scheduler_version=scheduler_version,
                    ),
                    _redis_pending(redis, stream=stream, group=group),
                ),
                timeout=min(5.0, remaining),
            )
            redis_failure = None
            postgres_failure = None
            committed = int(latest["inbound_statuses"].get("committed", 0))
            turns_committed = int(latest["turn_statuses"].get("committed", 0))
            mailbox_complete = scheduler_version != SchedulerVersion.V2 or (
                int(latest.get("mailbox_expected_count", 0)) > 0
                and int(latest.get("mailbox_row_count", 0))
                == int(latest.get("mailbox_expected_count", 0))
                and int(latest.get("mailbox_idle_count", 0))
                == int(latest.get("mailbox_expected_count", 0))
                and int(latest.get("mailbox_settled_count", 0))
                == int(latest.get("mailbox_expected_count", 0))
                and int(latest.get("mailbox_unresolved_item_count", 0)) == 0
            )
            if (
                committed == expected
                and turns_committed == expected
                and latest["published_scheduler_outbox"] >= expected_outbox
                and latest["leased_sessions"] == 0
                and mailbox_complete
                and latest_redis is not None
                and latest_redis["pending"] <= baseline_pending
            ):
                return {
                    "status": "pass",
                    "state": _public_state(latest),
                    "redis": latest_redis,
                }
        except RedisError as error:
            latest_redis = None
            redis_failure = _safe_failure(error)
        except asyncpg.PostgresError as error:
            postgres_failure = _safe_failure(error)
        except (OSError, RuntimeError):
            pass
        await asyncio.sleep(0.25)
    result: dict[str, Any] = {
        "status": "fail",
        "reason": "batch did not commit and drain before timeout",
        "state": _public_state(latest),
        "redis": latest_redis,
    }
    if redis_failure is not None:
        result["redis_failure"] = redis_failure
    if postgres_failure is not None:
        result["postgres_failure"] = postgres_failure
    return result


def _public_state(state: dict[str, Any]) -> dict[str, Any]:
    return {
        "inbound_statuses": state.get("inbound_statuses", {}),
        "turn_statuses": state.get("turn_statuses", {}),
        "published_inbound_outbox": state.get("published_inbound_outbox", 0),
        "published_scheduler_outbox": state.get("published_scheduler_outbox", 0),
        "scheduler_version": state.get("scheduler_version"),
        "leased_sessions": state.get("leased_sessions", 0),
        "mailbox_expected_count": state.get("mailbox_expected_count", 0),
        "mailbox_row_count": state.get("mailbox_row_count", 0),
        "mailbox_idle_count": state.get("mailbox_idle_count", 0),
        "mailbox_settled_count": state.get("mailbox_settled_count", 0),
        "mailbox_unresolved_item_count": state.get("mailbox_unresolved_item_count", 0),
    }


def _phase_gate(
    phase: dict[str, Any],
    completion: dict[str, Any],
    *,
    required_p95_ms: float,
) -> dict[str, Any]:
    accepted = int(phase.get("accepted", 0))
    requested = int(phase.get("requested", 0))
    errors = int(phase.get("errors", 0))
    p95 = _finite_parameter(phase.get("ack_p95_ms"))
    state = completion.get("state", {})
    inbound = state.get("inbound_statuses", {})
    turns = state.get("turn_statuses", {})
    mailbox_complete = True
    if state.get("scheduler_version") == SchedulerVersion.V2.value:
        mailbox_expected = int(state.get("mailbox_expected_count", 0))
        mailbox_complete = (
            mailbox_expected > 0
            and int(state.get("mailbox_row_count", 0)) == mailbox_expected
            and int(state.get("mailbox_idle_count", 0)) == mailbox_expected
            and int(state.get("mailbox_settled_count", 0)) == mailbox_expected
            and int(state.get("mailbox_unresolved_item_count", 0)) == 0
        )
    authoritative_lookup = phase.get("authoritative_lookup")
    lookup_passed = True
    if phase.get("mode") == "synthetic_encrypted_feishu_http":
        lookup_passed = (
            isinstance(authoritative_lookup, Mapping)
            and authoritative_lookup.get("status") == "pass"
        )
    passed = bool(
        accepted == requested
        and errors == 0
        and p95 is not None
        and p95 >= 0.0
        and p95 < required_p95_ms
        and lookup_passed
        and completion.get("status") == "pass"
        and int(inbound.get("committed", 0)) == requested
        and int(turns.get("committed", 0)) == requested
        and mailbox_complete
    )
    return {
        "status": "pass" if passed else "fail",
        "accepted_message_loss": requested - accepted,
        "uncommitted_turns": requested - int(turns.get("committed", 0)),
        "mailbox_complete": mailbox_complete,
        "ack_p95_headroom_ms": (required_p95_ms - p95) if p95 is not None else None,
    }


def _production_gate_reasons(
    args: argparse.Namespace,
    workload_passed: bool,
    *,
    max_turn_overlap_observed: int | None = None,
    burst_session_ids: Sequence[str] | None = None,
    burst_accepted: int | None = None,
    accepted_inbound_ids: Sequence[str] | None = None,
    baseline_redis_pending: int | None = None,
    final_redis_pending: int | None = None,
    actual_submission_start_rate_per_second: float | None = None,
    burst_actual_submission_start_rate_per_second: float | None = None,
    worker_image_attestation: Mapping[str, Any] | None = None,
    sustained_http_phase: Mapping[str, Any] | None = None,
    memory_observation: Mapping[str, Any] | None = None,
) -> list[str]:
    if not workload_passed:
        return ["sustained or burst performance phase failed"]
    if (
        args.callbacks < DEFAULT_CALLBACKS
        or not math.isfinite(args.callback_rate)
        or args.callback_rate < DEFAULT_CALLBACK_RATE
        or args.burst_turns < DEFAULT_BURST_TURNS
        or int(getattr(args, "min_workers", DEFAULT_MIN_WORKERS)) < PRODUCTION_MIN_WORKERS
    ):
        return []

    reasons: list[str] = []
    if sustained_http_phase is None:
        reasons.append("sustained HTTP callback phase evidence is unavailable")
    else:
        if sustained_http_phase.get("mode") != "synthetic_encrypted_feishu_http":
            reasons.append("sustained performance evidence is not an encrypted Feishu HTTP phase")
        try:
            http_requested = int(sustained_http_phase.get("requested", -1))
        except (TypeError, ValueError):
            http_requested = -1
        try:
            http_accepted = int(sustained_http_phase.get("accepted", -1))
        except (TypeError, ValueError):
            http_accepted = -1
        try:
            http_errors = int(sustained_http_phase.get("errors", -1))
        except (TypeError, ValueError):
            http_errors = -1
        if http_requested != args.callbacks:
            reasons.append("sustained HTTP requested count does not match the locked target")
        if http_accepted != args.callbacks:
            reasons.append("sustained HTTP accepted count does not match the locked target")
        if http_errors != 0:
            reasons.append("sustained HTTP callback errors were recorded")
        lookup = sustained_http_phase.get("authoritative_lookup")
        if not isinstance(lookup, Mapping) or lookup.get("status") != "pass":
            reasons.append("sustained HTTP callbacks lack complete authoritative inbound rows")
        gateway = sustained_http_phase.get("gateway")
        if not isinstance(gateway, Mapping) or gateway.get("host_class") != "loopback":
            reasons.append("sustained HTTP gateway loopback proof is unavailable")
        try:
            http_p95 = float(sustained_http_phase.get("ack_p95_ms", float("nan")))
        except (TypeError, ValueError):
            http_p95 = float("nan")
        if not math.isfinite(http_p95) or http_p95 >= DEFAULT_P95_MS:
            reasons.append("sustained HTTP callback p95 must be below 200ms")
        try:
            accepted_external_count = int(
                sustained_http_phase.get("accepted_external_message_id_count", -1)
            )
        except (TypeError, ValueError):
            accepted_external_count = -1
        if accepted_external_count != args.callbacks:
            reasons.append("sustained HTTP accepted external message IDs are incomplete")
        try:
            http_start_rate = float(
                sustained_http_phase.get("actual_submission_start_rate_per_second", float("nan"))
            )
        except (TypeError, ValueError):
            http_start_rate = float("nan")
        if not math.isfinite(http_start_rate) or http_start_rate < DEFAULT_CALLBACK_RATE:
            reasons.append(
                "sustained HTTP actual_submission_start_rate_per_second must be at least "
                f"{DEFAULT_CALLBACK_RATE:g}"
            )
    if worker_image_attestation is None or worker_image_attestation.get("status") != "pass":
        reason = (
            worker_image_attestation.get("reason") if worker_image_attestation is not None else None
        )
        reasons.append(
            str(reason)
            if isinstance(reason, str) and reason
            else "worker image attestation is unavailable"
        )
    if actual_submission_start_rate_per_second is None:
        reasons.append("sustained actual_submission_start_rate_per_second was not recorded")
    else:
        try:
            actual_start_rate = float(actual_submission_start_rate_per_second)
        except (TypeError, ValueError):
            actual_start_rate = float("nan")
        if not math.isfinite(actual_start_rate) or actual_start_rate < DEFAULT_CALLBACK_RATE:
            reasons.append(
                "sustained actual_submission_start_rate_per_second must be at least "
                f"{DEFAULT_CALLBACK_RATE:g}"
            )

    if burst_actual_submission_start_rate_per_second is None:
        reasons.append("burst actual_submission_start_rate_per_second was not recorded")
    else:
        try:
            burst_start_rate = float(burst_actual_submission_start_rate_per_second)
        except (TypeError, ValueError):
            burst_start_rate = float("nan")
        if not math.isfinite(burst_start_rate) or burst_start_rate < DEFAULT_CALLBACK_RATE:
            reasons.append(
                "burst actual_submission_start_rate_per_second must be at least "
                f"{DEFAULT_CALLBACK_RATE:g}"
            )

    if max_turn_overlap_observed is None:
        reasons.append("actual max_turn_overlap_observed was not recorded")
    else:
        try:
            overlap = float(max_turn_overlap_observed)
        except (TypeError, ValueError):
            overlap = float("nan")
        if not math.isfinite(overlap) or overlap < DEFAULT_BURST_TURNS:
            reasons.append(
                f"actual max_turn_overlap_observed must be at least {DEFAULT_BURST_TURNS}"
            )

    if burst_session_ids is None:
        reasons.append("burst session IDs were not recorded")
    else:
        session_count = len(burst_session_ids)
        if session_count != len(set(burst_session_ids)):
            reasons.append("burst session IDs must be unique")
        if session_count < DEFAULT_BURST_TURNS:
            reasons.append(f"burst session IDs must contain at least {DEFAULT_BURST_TURNS} entries")
        if burst_accepted is None:
            reasons.append("burst accepted callback count was not recorded")
        elif burst_accepted < DEFAULT_BURST_TURNS:
            reasons.append(f"burst accepted callback count must be at least {DEFAULT_BURST_TURNS}")
        elif session_count != burst_accepted:
            reasons.append("burst session ID count must equal accepted callback count")

    if accepted_inbound_ids is None:
        reasons.append("accepted inbound IDs were not recorded")
    elif len(accepted_inbound_ids) != len(set(accepted_inbound_ids)):
        reasons.append("accepted inbound IDs must be unique")

    if baseline_redis_pending != 0:
        reasons.append("baseline Redis pending must be exactly 0")
    if final_redis_pending != 0:
        reasons.append("final Redis pending must be exactly 0")
    if memory_observation is not None:
        if memory_observation.get("status") != "pass":
            reasons.append("real worker/service peak memory evidence is unavailable")
        if memory_observation.get("coverage_complete") is not True:
            reasons.append("real worker/service peak memory evidence coverage is incomplete")
        if memory_observation.get("within_safety_threshold") is not True:
            reasons.append("observed worker/service peak memory exceeds its safety threshold")
    return reasons


def _production_gate_status(
    args: argparse.Namespace,
    workload_passed: bool,
    *,
    max_turn_overlap_observed: int | None = None,
    burst_session_ids: Sequence[str] | None = None,
    burst_accepted: int | None = None,
    accepted_inbound_ids: Sequence[str] | None = None,
    baseline_redis_pending: int | None = None,
    final_redis_pending: int | None = None,
    actual_submission_start_rate_per_second: float | None = None,
    burst_actual_submission_start_rate_per_second: float | None = None,
    worker_image_attestation: Mapping[str, Any] | None = None,
    sustained_http_phase: Mapping[str, Any] | None = None,
    memory_observation: Mapping[str, Any] | None = None,
) -> str:
    if not workload_passed:
        return "fail"
    if (
        args.callbacks < DEFAULT_CALLBACKS
        or not math.isfinite(args.callback_rate)
        or args.callback_rate < DEFAULT_CALLBACK_RATE
        or args.burst_turns < DEFAULT_BURST_TURNS
        or int(getattr(args, "min_workers", DEFAULT_MIN_WORKERS)) < PRODUCTION_MIN_WORKERS
    ):
        return "not_run"
    if worker_image_attestation is None or worker_image_attestation.get("status") != "pass":
        return "not_run"
    if sustained_http_phase is None:
        return "not_run"
    if memory_observation is not None and memory_observation.get("status") == "not_run":
        return "not_run"
    return (
        "pass"
        if not _production_gate_reasons(
            args,
            workload_passed,
            max_turn_overlap_observed=max_turn_overlap_observed,
            burst_session_ids=burst_session_ids,
            burst_accepted=burst_accepted,
            accepted_inbound_ids=accepted_inbound_ids,
            baseline_redis_pending=baseline_redis_pending,
            final_redis_pending=final_redis_pending,
            actual_submission_start_rate_per_second=actual_submission_start_rate_per_second,
            burst_actual_submission_start_rate_per_second=burst_actual_submission_start_rate_per_second,
            worker_image_attestation=worker_image_attestation,
            sustained_http_phase=sustained_http_phase,
            memory_observation=memory_observation,
        )
        else "fail"
    )


def _redis_pending_delta(baseline: dict[str, int], final: Any) -> int | None:
    if not isinstance(final, dict) or "pending" not in final:
        return None
    return int(final["pending"]) - int(baseline["pending"])


